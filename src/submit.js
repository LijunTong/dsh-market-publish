/**
 * The `--apply` path: fork the list, commit the entry on a branch, open the
 * pull request. Every network call goes through the injected client.
 */

export const UPSTREAM = 'awesome-dsh-plugin/awesome-dsh-plugin'
export const UPSTREAM_BRANCH = 'main'
export const FORK_WAIT_MS = 3000
export const FORK_ATTEMPTS = 20

/**
 * Branch names have to stay stable across reruns so a retry updates the same
 * branch instead of opening a second pull request.
 *
 * @param {string} repo
 */
export function branchName(repo) {
  return `add-${repo.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`
}

/**
 * @param {{ repo: string, category: string, notes: readonly string[], entryPath: string }} options
 */
export function pullRequestBody(options) {
  return [
    `Adds **${options.repo}** under \`${options.category}\`.`,
    '',
    'Checked before opening this pull request:',
    '',
    ...options.notes.map((note) => `- ${note}`),
    `- entry file only: \`${options.entryPath}\``,
    '',
    'READMEs are generated by this list, so nothing else is touched.',
  ].join('\n')
}

/**
 * @param {{
 *   client: { request: (path: string, init?: any) => Promise<any>, orThrow: (path: string, init?: any) => Promise<any> },
 *   repo: string,
 *   category: string,
 *   entry: string,
 *   entryPath: string,
 *   notes: readonly string[],
 *   upstream?: string,
 *   upstreamBranch?: string,
 *   log?: (line: string) => void,
 *   sleep?: (ms: number) => Promise<void>,
 *   forkAttempts?: number,
 *   forkWaitMs?: number,
 * }} options
 * @returns {Promise<{ url: string, branch: string, fork: string }>}
 */
export async function submitEntry(options) {
  const upstream = options.upstream ?? UPSTREAM
  const upstreamBranch = options.upstreamBranch ?? UPSTREAM_BRANCH
  const log = options.log ?? (() => {})
  const sleep = options.sleep ?? ((ms) => new Promise((resolve) => setTimeout(resolve, ms)))
  const attempts = options.forkAttempts ?? FORK_ATTEMPTS
  const waitMs = options.forkWaitMs ?? FORK_WAIT_MS
  const { client, repo, entry, entryPath } = options

  if (client.token === '') {
    throw new Error('--apply 需要 token：设置 GITHUB_TOKEN（或 GH_TOKEN），或先 gh auth login')
  }

  const me = (await client.orThrow('/user')).login
  const fork = `${me}/${upstream.split('/')[1]}`
  log(`→ fork ${upstream} → ${fork}`)
  await client.request(`/repos/${upstream}/forks`, { method: 'POST', body: { default_branch_only: false } })

  let ready = false
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    const probe = await client.request(`/repos/${fork}`)
    if (probe.ok) {
      ready = true
      break
    }
    await sleep(waitMs)
  }
  if (!ready) throw new Error(`fork ${fork} 未就绪，稍后重试`)

  const branch = branchName(repo)
  const base = await client.orThrow(`/repos/${fork}/git/ref/heads/${upstreamBranch}`)
  const baseSha = base.object.sha
  const existing = await client.request(`/repos/${fork}/git/ref/heads/${branch}`)
  if (!existing.ok) {
    log(`→ branch ${branch}`)
    await client.orThrow(`/repos/${fork}/git/refs`, {
      method: 'POST',
      body: { ref: `refs/heads/${branch}`, sha: baseSha },
    })
  }

  const current = await client.request(`/repos/${fork}/contents/${entryPath}?ref=${branch}`)
  /** @type {any} */
  const put = {
    message: `Add ${repo}`,
    content: Buffer.from(entry, 'utf8').toString('base64'),
    branch,
  }
  if (current.ok && current.data && typeof current.data.sha === 'string') put.sha = current.data.sha
  log(`→ ${entryPath}`)
  await client.orThrow(`/repos/${fork}/contents/${entryPath}`, { method: 'PUT', body: put })

  const pull = await client.request(`/repos/${upstream}/pulls`, {
    method: 'POST',
    body: {
      title: `Add ${repo}`,
      head: `${me}:${branch}`,
      base: upstreamBranch,
      body: pullRequestBody({ repo, category: options.category, notes: options.notes, entryPath }),
    },
  })
  if (!pull.ok) {
    const message = pull.data && typeof pull.data === 'object' ? pull.data.message : pull.status
    if (String(message).includes('already exists')) {
      throw new Error(`已有针对 ${me}:${branch} 的 PR，去 ${upstream} 看一下`)
    }
    throw new Error(`创建 PR 失败：${pull.status} ${message}`)
  }
  return { url: pull.data.html_url, branch, fork }
}
